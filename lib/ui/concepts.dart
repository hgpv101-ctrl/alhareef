  const ConceptsScreen({super.key});
  @override
  State<ConceptsScreen> createState() => _ConceptsS();
}

class _ConceptsS extends State<ConceptsScreen> {
  String q = '';

  @override
  Widget build(BuildContext context) {
    final key = q.trim();
    final secs = <Widget>[];
    for (final s in _secs) {
      final items = [for (final it in s.items) if (key.isEmpty || it[0].contains(key) || it[1].contains(key)) it];
      if (items.isEmpty) continue;
      secs.add(Card(
        margin: const EdgeInsets.only(bottom: 10),
        child: Theme(
          data: Theme.of(context).copyWith(dividerColor: Colors.transparent),
          child: ExpansionTile(
            key: PageStorageKey('${s.title}$key'),
            initiallyExpanded: key.isNotEmpty,
            leading: Text(s.icon, style: const TextStyle(fontSize: 24)),
            title: Text(s.title, style: const TextStyle(fontWeight: FontWeight.w800)),
            childrenPadding: const EdgeInsets.fromLTRB(16, 0, 16, 12),
            expandedCrossAxisAlignment: CrossAxisAlignment.start,
            children: [
              for (final it in items)
                Padding(
                  padding: const EdgeInsets.only(bottom: 10),
                  child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
                    Text(it[0], style: const TextStyle(fontWeight: FontWeight.w800, color: C.purple)),
                    const SizedBox(height: 2),
                    Text(it[1], style: const TextStyle(height: 1.5)),
                  ]),
                ),
            ],
          ),
        ),
      ));
    }
    return Scaffold(
      appBar: AppBar(title: const Text('📖 مفاهيم')),
      body: ListView(padding: const EdgeInsets.all(14), children: [
        TextField(
          onChanged: (v) => setState(() => q = v),
          decoration: const InputDecoration(hintText: 'ابحث عن أي خانة أو مفهوم...', prefixIcon: Icon(Icons.search)),
        ),
        const SizedBox(height: 12),
        if (secs.isEmpty) const Padding(padding: EdgeInsets.all(40), child: Center(child: Text('مفيش نتيجة.', style: TextStyle(color: Colors.grey)))),
        ...secs,
      ]),
    );
  }
